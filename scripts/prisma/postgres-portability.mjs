/**
 * Owned, temporary PostgreSQL fixture for issue #52. It never accepts a
 * connection string from the caller and it only cleans up state it created.
 */
import { randomBytes } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, isAbsolute, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const repo = process.cwd();
const prefix = "watchnext-postgres-portability-";
const compose = join(repo, "docker", "postgres-portability.compose.yml");
const schema = join(repo, "prisma", "postgresql", "schema.prisma");
const prisma = join(repo, "node_modules", "prisma", "build", "index.js");
const stateName = ".postgres-portability-state.json";

function fail(message) { throw new Error(message); }
function run(command, args, { env = process.env, quiet = false } = {}) {
  const result = spawnSync(command, args, { cwd: repo, env, encoding: "utf8", windowsHide: true });
  if (result.error) fail(`${command} could not start: ${result.error.message}`);
  if (result.status !== 0) fail(`${command} ${args.join(" ")} failed.\n${result.stdout ?? ""}${result.stderr ?? ""}`.trim());
  if (!quiet && result.stdout) process.stdout.write(result.stdout);
  return result.stdout.trim();
}
function dockerAvailable() {
  const result = spawnSync("docker", ["compose", "version"], { cwd: repo, encoding: "utf8", windowsHide: true });
  if (result.error || result.status !== 0) fail("PostgreSQL portability requires Docker Desktop with Docker Compose. Install and start Docker, then rerun; no PostgreSQL proof ran.");
}
function statePath(root) { return join(root, stateName); }
function validRoot(root) {
  const temp = resolve(tmpdir()); const candidate = resolve(root);
  return candidate.startsWith(`${temp}\\`) || candidate.startsWith(`${temp}/`) ? basename(candidate).startsWith(prefix) : false;
}
function readState(value) {
  const path = resolve(value);
  if (!isAbsolute(value) || !existsSync(path)) fail("Provide an existing absolute --state path emitted by prisma:postgres:start.");
  const parsed = JSON.parse(readFileSync(path, "utf8"));
  if (!parsed || typeof parsed.root !== "string" || !validRoot(parsed.root) || resolve(parsed.root) !== resolve(join(path, "..")) || resolve(parsed.compose ?? "") !== resolve(compose) || !/^watchnext-portability-[a-z0-9-]+$/i.test(parsed.project ?? "")) fail("Refusing to use an unowned PostgreSQL portability state file.");
  return { ...parsed, path };
}
function argument(name) {
  const index = process.argv.indexOf(name);
  return index < 0 ? undefined : process.argv[index + 1];
}
function url(port, password) { return `postgresql://watchnext:${encodeURIComponent(password)}@127.0.0.1:${port}/watchnext?schema=public`; }
function start() {
  dockerAvailable();
  const root = mkdtempSync(join(tmpdir(), prefix));
  const project = `watchnext-portability-${process.pid}-${randomBytes(5).toString("hex")}`;
  const password = randomBytes(24).toString("base64url");
  const env = { ...process.env, WATCHNEXT_POSTGRES_PASSWORD: password };
  try {
    run("docker", ["compose", "-p", project, "-f", compose, "up", "--detach", "--wait"], { env });
    const published = run("docker", ["compose", "-p", project, "-f", compose, "port", "postgres", "5432"], { env, quiet: true });
    const match = /:(\d+)\s*$/.exec(published);
    if (!match) fail("Docker did not report an owned PostgreSQL port.");
    const databaseUrl = url(match[1], password);
    const state = { version: 1, root, project, compose, databaseUrl, createdAt: new Date().toISOString() };
    writeFileSync(statePath(root), JSON.stringify(state, null, 2), { mode: 0o600 });
    const prismaEnv = { ...env, WATCHNEXT_POSTGRES_URL: databaseUrl };
    run(process.execPath, [prisma, "generate", "--schema", schema], { env: prismaEnv });
    run(process.execPath, [prisma, "migrate", "deploy", "--schema", schema], { env: prismaEnv });
    console.log(`PASS: owned disposable PostgreSQL is ready. State: ${statePath(root)}`);
    console.log(`Run pnpm prisma:postgres:verify -- --state ${statePath(root)} then pnpm prisma:postgres:cleanup -- --state ${statePath(root)}`);
    return state;
  } catch (error) {
    try { run("docker", ["compose", "-p", project, "-f", compose, "down", "--volumes", "--remove-orphans"], { env, quiet: true }); } catch {}
    rmSync(root, { recursive: true, force: true });
    throw error;
  }
}
function cleanup(path) {
  const state = readState(path); dockerAvailable();
  // The project and compose path were generated by this script and state root
  // is constrained to the OS temporary directory before Docker is called.
  run("docker", ["compose", "-p", state.project, "-f", state.compose, "down", "--volumes", "--remove-orphans"], { quiet: true });
  rmSync(state.root, { recursive: true, force: true });
  console.log("PASS: removed the owned disposable PostgreSQL instance and its temporary state.");
}
function verify(path) {
  const state = path ? readState(path) : start();
  dockerAvailable();
  const env = { ...process.env, WATCHNEXT_HTTP_REPOSITORY: "prisma", WATCHNEXT_HTTP_PRISMA_PROVIDER: "postgresql", WATCHNEXT_HTTP_PRISMA_DATABASE_URL: state.databaseUrl, WATCHNEXT_POSTGRES_URL: state.databaseUrl, WATCHNEXT_HTTP_METADATA_FIXTURES: "1", NEXT_TELEMETRY_DISABLED: "1" };
  run(process.execPath, ["scripts/prisma/sqlite-portability.mjs"]);
  run(process.execPath, ["tests/fixtures/postgres-portability-check.mjs"], { env: { ...env, WATCHNEXT_PORTABILITY_PROVIDER: "postgresql" } });
  console.log("PASS: matching SQLite and PostgreSQL mapping, HTTP/browser, and server-restart journeys completed against owned disposable databases.");
  if (!path) cleanup(statePath(state.root));
}

const command = process.argv[2];
try {
  if (command === "start") start();
  else if (command === "verify") verify(argument("--state"));
  else if (command === "cleanup") cleanup(argument("--state"));
  else fail("Use start, verify, or cleanup. Example: pnpm prisma:postgres:start");
} catch (error) {
  console.error(`FAIL: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
}
