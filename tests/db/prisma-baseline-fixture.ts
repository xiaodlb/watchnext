type Row = Record<string, unknown>;

/** Track open handles per file so a test can prove native and Prisma never overlap on one file. */
export const openHandles = { native: new Map<string, number>(), prisma: new Map<string, number>() };
function bump(map: Map<string, number>, path: string, delta: number) {
  const next = (map.get(path) ?? 0) + delta;
  if (next) map.set(path, next); else map.delete(path);
}
export function markOpen(kind: "native" | "prisma", path: string): void {
  const other = kind === "native" ? openHandles.prisma : openHandles.native;
  if (other.has(path)) throw new Error(`Refusing to open ${kind} on a file that has an open ${kind === "native" ? "Prisma" : "native"} connection`);
  bump(openHandles[kind], path, 1);
}
export function markClosed(kind: "native" | "prisma", path: string): void { bump(openHandles[kind], path, -1); }

/** Open, use and always close one native connection. Throws if a Prisma connection holds the same file. */
export function withNative<T>(path: string, work: (db: DatabaseSync) => T, options: { readOnly?: boolean } = {}): T {
  markOpen("native", path);
  const db = new DatabaseSync(path, { readOnly: options.readOnly ?? false });
  try {
    db.exec("PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;");
    return work(db);
  } finally {
    db.close();
    markClosed("native", path);
  }
}

function plain(row: unknown): Row { return { ...(row as Row) }; }
function all(db: DatabaseSync, sql: string, ...params: (string | number | null)[]): Row[] {
  return db.prepare(sql).all(...params).map(plain);
}

export function migrationFiles(): string[] {
  return readdirSync(migrationDirectory).filter((name) => /^\d{4}_[a-z0-9_]+\.sql$/.test(name)).sort();
}

/** SHA-256 of each committed native migration, CRLF-normalized exactly like db/migrate.ts. */
export function nativeLedger(): { version: string; filename: string; checksum: string }[] {
  return migrationFiles().map((filename) => ({
    version: filename.slice(0, 4),
    filename,
    checksum: createHash("sha256").update(readFileSync(join(migrationDirectory, filename), "utf8").replace(/\r\n/g, "\n")).digest("hex"),
  }));
}

function quote(value: string): string { return `'${value.replace(/'/g, "''")}'`; }

/**
 * Canonical baseline dump (prisma-baseline §6): header, every named sqlite_master row with SQL in
 * rowid order, the five mood rows and the five native ledger rows with committed-file checksums.
 */
export function canonicalDump(db: DatabaseSync): string {
  const lines = ["-- WatchNext Prisma baseline (issue #48): canonical dump of native db/migrations 0001-0005. Generated by tests/db/prisma-baseline.test.ts; never edit. Native SQL stays the SQLite DDL authority."];
  for (const row of all(db, "SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' AND name <> '_prisma_migrations' ORDER BY rowid")) {
    lines.push(`${row.sql as string};`);
  }
  for (const mood of all(db, "SELECT code, label FROM moods ORDER BY rowid")) {
    lines.push(`INSERT INTO moods(code, label) VALUES (${quote(mood.code as string)}, ${quote(mood.label as string)});`);
  }
  for (const entry of nativeLedger()) {
    lines.push(`INSERT INTO schema_migrations(version, filename, checksum) VALUES (${quote(entry.version)}, ${quote(entry.filename)}, ${quote(entry.checksum)});`);
  }
  return `${lines.join("\n")}\n`;
}

export type Inventory = {
  master: Row[];
  counts: { tables: number; triggers: number; explicitIndexes: number; partialIndexes: number; autoindexes: number; strictTables: number };
  strict: Row[];
  foreignKeys: Row[];
  ledger: Row[];
  moods: Row[];
};

/** Canonical schema inventory (I1). `_prisma_migrations` and its autoindex are the only exclusions. */
export function inventory(db: DatabaseSync): Inventory {
  const master = all(db, `SELECT type, name, tbl_name, sql FROM sqlite_master
    WHERE name <> '_prisma_migrations' AND name NOT LIKE 'sqlite\\_autoindex\\_\\_prisma\\_migrations%' ESCAPE '\\'
    ORDER BY type, name`);
  const tables = master.filter((row) => row.type === "table" && !String(row.name).startsWith("sqlite_")).map((row) => String(row.name));
  const partialIndexes = tables.reduce((sum, table) => sum + all(db, "SELECT name FROM pragma_index_list(?) WHERE partial = 1", table).length, 0);
  const strict = all(db, "SELECT name, strict FROM pragma_table_list WHERE schema = 'main' AND type = 'table' AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' AND name <> '_prisma_migrations' ORDER BY name");
  const foreignKeys = tables.sort().flatMap((table) => all(db, 'SELECT ? AS "from_table", id, seq, "table", "from", "to", on_update, on_delete FROM pragma_foreign_key_list(?) ORDER BY id, seq', table, table));
  return {
    master,
    counts: {
      tables: tables.length,
      triggers: master.filter((row) => row.type === "trigger").length,
      explicitIndexes: master.filter((row) => row.type === "index" && row.sql !== null).length,
      partialIndexes,
      autoindexes: master.filter((row) => row.type === "index" && row.sql === null).length,
      strictTables: strict.filter((row) => row.strict === 1).length,
    },
    strict,
    foreignKeys,
    ledger: all(db, "SELECT version, filename, checksum FROM schema_migrations ORDER BY version"),
    moods: all(db, "SELECT code, label FROM moods ORDER BY code"),
  };
}

/** Every row of all 19 tables, ordered by primary key; includes hashes, tuples, deadlines and history. */
export function logicalSnapshot(db: DatabaseSync): Record<string, Row[]> {
  const snapshot: Record<string, Row[]> = {};
  for (const table of TABLES) {
    const keys = all(db, "SELECT name FROM pragma_table_info(?) WHERE pk > 0 ORDER BY pk", table).map((row) => `"${String(row.name)}"`);
    snapshot[table] = all(db, `SELECT * FROM "${table}" ORDER BY ${keys.join(", ")}`);
  }
  return snapshot;
}

export function integrity(db: DatabaseSync): { integrity: unknown; foreignKeyViolations: number } {
  return {
    integrity: (db.prepare("PRAGMA integrity_check").get() as Row).integrity_check,
    foreignKeyViolations: db.prepare("PRAGMA foreign_key_check").all().length,
  };
}

/** Fresh native database at the current revision, as `pnpm db:init` would create it (path A start). */
export function createNativeDatabase(path: string): void {
  withNative(path, (db) => { migrate(db); });
}

